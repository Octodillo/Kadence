# Write the PKGBUILD of the release package (kadence) from the development
# one (kadence-git, ./PKGBUILD), so the two cannot drift apart: dependencies,
# build(), check() and package() are the same text. Only the header, the
# package name and the "kadence-git only" part differ; that part becomes the
# release tarball made by packaging/make-dist.sh, which vendors every crate.
#
#   packaging/arch/release-pkgbuild.sh VERSION [TARBALL] > PKGBUILD
#
# With TARBALL its sha256 is filled in; without, the checksum is SKIP (for
# linting only). To build a local tarball, put it next to the PKGBUILD.
set -eu

version=${1:?usage: $0 VERSION [TARBALL]}
sum=SKIP
if [ $# -ge 2 ]; then
    sum=$(sha256sum "$2" | cut -d' ' -f1)
fi
here=$(dirname "$0")

awk -v version="$version" -v sum="$sum" '
    BEGIN { header = 1 }
    header && /^#/ {
        if (!/^# (SPDX|Maintainer)/) next
        print; next
    }
    header {
        header = 0
        print "#"
        print "# Release package, built offline from the source tarball attached to the"
        print "# GitHub release. Generated by packaging/arch/release-pkgbuild.sh from the"
        print "# development package (kadence-git); change that, not this file."
        seen["header"] = 1
    }
    /^pkgname=kadence-git$/ { print "pkgname=kadence"; seen["pkgname"] = 1; next }
    /^pkgver=/ { print "pkgver=" version; seen["pkgver"] = 1; next }
    /^# >>> kadence-git only$/ {
        skipping = 1
        print "conflicts=(kadence-git)"
        print "_srcdir=$pkgname-$pkgver"
        print "source=(\"$url/releases/download/v$pkgver/$pkgname-$pkgver.tar.gz\")"
        print "sha256sums=(" (sum == "SKIP" ? sum : "\x27" sum "\x27") ")"
        next
    }
    /^# <<< kadence-git only$/ { skipping = 0; seen["part"] = 1; next }
    !skipping { print }
    END {
        split("header pkgname pkgver part", need, " ")
        for (i in need) if (!seen[need[i]]) {
            print "release-pkgbuild: " need[i] " not found in PKGBUILD" > "/dev/stderr"
            exit 1
        }
    }
' "$here/PKGBUILD"
